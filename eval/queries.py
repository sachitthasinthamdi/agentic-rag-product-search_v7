def by_principle(pairs: list[dict] = TEST_PAIRS) -> dict[str, list[dict]]:
    """จัดกลุ่มตามหลักการที่ใช้ทดสอบ — ดูว่าโมเดลทำตามหลักการข้อไหนได้/ไม่ได้"""
    out: dict[str, list[dict]] = {}
    for pair in pairs:
        out.setdefault(pair.get("tests", "-"), []).append(pair)
    return out


