"""เขียนคำค้นใหม่สำหรับรอบถัดไปของลูป — ใช้โดย A3 และ A4

**ทำไมต้องมี:** ถ้าลูปค้นด้วยคำเดิมก็ได้ผลเดิม วนเท่าไหร่ก็ไม่ดีขึ้น

**ทำไมใช้ LLM ไม่ใช้โค้ด:** รุ่นแรกของ A3 ใช้บันไดโค้ดที่ตัดคำขยายออกทีละชั้น
แล้วพบว่า **มันตัดชื่อสินค้าทิ้ง**

    ถาม "ค้อนหงอนด้ามไฟเบอร์กลาสสำหรับงานช่าง" (คลังไม่มีค้อนหงอน)
    รอบ 1  'เครื่องมือ ค้อนหงอน'  -> ผ่านประตู 0    ถูกต้อง
    รอบ 2  'เครื่องมือ'           -> ผ่านประตู 7    **ตอบด้วยซองใส่เครื่องมือ**

A2 ตอบ "ไม่พบสินค้าที่ตรงกับที่ขอ" ซึ่งถูก แต่ A3 ตอบผิดเพราะลูปทำให้คำค้นกว้างลง
สาเหตุ: Memory จัด "ค้อนหงอน" เป็น `features_wanted` และ "เครื่องมือ" เป็น `category`
บันไดจึงตัดชื่อสินค้าทิ้งแล้วเก็บหมวดกว้างไว้ — กลับหัวกับที่ควรเป็น

**การเขียนคำค้นใหม่เป็นงานภาษา ไม่ใช่งานตัวเลข** และขั้น 5.6 วัดไว้ว่า

| ชนิดการตัดสินใจ | LLM κ | โค้ด κ |
|---|---|---|
| เรื่องภาษา (นี่คือข้อนี้) | **0.646** | 0.280 |
| เรื่องตัวเลข (หยุดหรือวนต่อ) | 0.000-0.676 | **0.824** |

→ **ใช้ LLM เขียนคำค้น · ใช้โค้ดตัดสินว่าจะหยุด** ตามที่หลักฐานบอก

⚠ **ผลที่ต้องยอมรับ:** A3 จึงไม่ใช่ "ทำซ้ำได้ 100%" อีกต่อไป เพราะมี LLM อยู่ในลูป
A3 ยังเรียกว่า "โค้ดคุม" ได้ เพราะโค้ดคุม**การตัดสินใจว่าจะวนไหม** ซึ่งเป็นตัวแปร
ที่ A3 กับ A4 ต่างกันตาม `docs/architecture.md`

**คืนภาษาอังกฤษตรง ๆ** → รอบที่ 2 ขึ้นไปไม่ต้องเรียกชั้นแปลอีก
**คืน `None` เมื่อคิดคำใหม่ไม่ได้** → ลูปหยุดแล้วตอบว่าไม่พบ ซึ่งดีกว่าตอบของผิด

⚠ **ทดลองแล้วไม่ผ่าน อย่าทำซ้ำ** (15 ต.ค. 2026 · docs/steps.md ข้อ 238-239)
เคยลองส่ง*ชื่อสินค้าที่ค้นมาได้แต่ไม่ตรง*เข้ามาในพรอมต์ เพื่อให้โมเดลรู้ว่าผลผิดอย่างไร
ผลคือ **แย่ลง** — โมเดล 8B ไม่ได้เรียนรู้ว่าต้องเลี่ยง แต่ยอมแพ้ (ตอบ NONE) หรือไขว้เขว
ไปตามคำผิวเผิน (`serta kleinmon` + ชื่อสินค้าที่ผิด -> `calvin klein men's t-shirt`)
เพราะการเอาผลที่ผิดของตัวเองกลับไปให้โมเดลวิจารณ์ **คือ self-refine**
ซึ่งโปรเจกต์นี้วัดและปฏิเสธไปแล้วในขั้น 135 (Entrospect ACL 2025 · Huang et al. 2024 ICLR)

⚠ ต้องสตาร์ต Ollama ก่อน:  ollama.exe serve
"""

from __future__ import annotations

import sys
from pathlib import Path

import httpx

sys.path.insert(0, str(Path(__file__).resolve().parent))
from embed import OLLAMA_URL                                     # noqa: E402
from memory import strip_budget                               # noqa: E402
from translate import CHAT_MODEL, _clean_output                  # noqa: E402

TIMEOUT = 180

# พรอมต์สั้นและเป็นคำถามเชิงภาษา ตามบทเรียนขั้น 5.2 (ย่อพรอมต์ครึ่งหนึ่งคะแนนไม่ตก)
# และขั้น 5.6 (ถามให้ตรงกับสิ่งที่โมเดลเก่ง)
REWRITE_SYSTEM = """คลังสินค้าเป็นภาษาอังกฤษ คำค้นที่ลองไปแล้วหาของที่ตรงไม่เจอ
เขียนคำค้นภาษาอังกฤษ**ใหม่** เพื่อหาสินค้า**ชนิดเดิม**

เก็บชนิดสินค้าไว้เสมอ      ค้อนหงอน -> claw hammer / hammer with claw
เปลี่ยนคำที่ใช้เรียกสินค้า   ที่นอนยางพารา -> latex mattress / natural rubber mattress
ตัดคำขยายที่อาจแคบเกินไป    ค้อนหงอนด้ามไฟเบอร์กลาส -> claw hammer
ห้ามเปลี่ยนเป็นสินค้าชนิดอื่น

ตอบเฉพาะคำค้นภาษาอังกฤษบรรทัดเดียว ห้ามอธิบาย ห้ามใส่เครื่องหมายคำพูด"""


def rewrite(want: str, tried: list[str],
            model: str = CHAT_MODEL) -> str | None:
    """คิดคำค้นภาษาอังกฤษใหม่ที่ไม่ซ้ำกับที่ลองไปแล้ว

    `want`  สิ่งที่ผู้ใช้อยากได้ (ภาษาไทยหรืออังกฤษก็ได้)
    `tried` คำค้นที่ลองไปแล้วและไม่ได้ผล

    คืน `None` เมื่อ **คิดคำใหม่ไม่ได้** — ต่อ Ollama ไม่ได้ · ผลยังมีอักษรไทย ·
    หรือได้คำที่ซ้ำกับที่ลองแล้ว → ลูปต้องหยุดและตอบว่าไม่พบ ไม่ใช่ขยายคำให้กว้างลง

        >>> rewrite("ค้อนหงอนด้ามไฟเบอร์กลาส", ["เครื่องมือ ค้อนหงอน"])
        'claw hammer'
    """
    user = (f'ผู้ใช้อยากได้: "{want}"\n'
            f"คำค้นที่ลองแล้วไม่ได้ผล: {' | '.join(tried) if tried else '(ยังไม่ได้ลอง)'}\n"
            f"เขียนคำค้นใหม่")
    try:
        response = httpx.post(
            f"{OLLAMA_URL}/api/chat", timeout=TIMEOUT,
            json={"model": model, "stream": False,
                  "options": {"temperature": 0, "seed": 0},
                  "messages": [{"role": "system", "content": REWRITE_SYSTEM},
                               {"role": "user", "content": user}]})
        response.raise_for_status()
        raw = response.json()["message"]["content"]
    except (httpx.HTTPError, KeyError, ValueError):
        return None

    # `_clean_output` คืน fallback เมื่อผลใช้ไม่ได้ (ว่าง / ยังมีอักษรไทย / ยาวเกิน)
    sentinel = "\x00"
    text = _clean_output(raw, fallback=sentinel)
    if text == sentinel:
        return None

    # ⚠ **ตัดงบออกจากคำที่ LLM เขียนมาด้วย** — บังคับด้วยโค้ด ไม่ฝากไว้กับพรอมต์
    # หลังแก้ชั้นความจำให้ตัดงบแล้ว ยังเหลือหลุด 1/30 เพราะรอบแรกค้นสะอาด
    # แต่ LLM เติมงบกลับเข้ามาเองตอนเขียนคำค้นใหม่
    #     รอบ 1  childproof cabinet lock
    #     รอบ 2  childproof cabinet lock under $6     <- เติมเอง
    text = strip_budget(text)
    if not text:
        return None

    low = text.strip().lower()
    if any(low == strip_budget(t).strip().lower() for t in tried):
        return None                       # คิดคำเดิม = ไม่มีอะไรใหม่ให้ลอง
    return text
