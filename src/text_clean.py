"""ทำความสะอาดข้อความสินค้า — ลบไอคอน/อีโมจิ แต่เก็บอักขระที่มีความหมายไว้

**หลักการ: ไม่ลบทุกอย่างที่ไม่ใช่ ASCII** เพราะหลายตัวมีความหมายจริง
`°` องศา · `×` ขนาด · `℃` อุณหภูมิ · `é` ในชื่อแบรนด์ · `± ≤ ≈` คณิตศาสตร์
ถ้าลบหมดจะเสียข้อมูลสเปกสินค้าไปโดยไม่จำเป็น

จากการสำรวจ `features` ทุกแถว (`tools/scan_features.py`) พบอักขระนอก ASCII
268,011 ครั้ง 1,851 ชนิด ใน 39.3% ของแถว แบ่งเป็น 3 พวก:

| พวก | ตัวอย่าง | ทำอะไร |
|---|---|---|
| ตัวอักษรที่ถูกเขียนด้วยรหัสแปลก | `𝐄𝐚𝐬𝐲 𝐭𝐨 𝐔𝐬𝐞` `①` `℃` `，` | **แปลงกลับ** เป็นตัวอักษรปกติ |
| เครื่องหมายที่มีคู่แบบ ASCII | `【】` `’ ”` `– —` | **แทนที่** ด้วยตัวที่เทียบเท่า |
| ไอคอนตกแต่งล้วน ๆ | 💛 ✅ ❤ ★ ➤ | **ลบทิ้ง** |
"""

from __future__ import annotations

import re
import unicodedata

# --- แทนที่ด้วยตัวที่เทียบเท่าใน ASCII ---------------------------------------
# 【】 พบมากที่สุดในข้อมูล (124,243 ครั้ง) ใช้คั่นหัวข้อแบบ 【Waterproof】รายละเอียด...
# จึงแปลงเป็น [ ] ไม่ใช่ลบทิ้ง เพราะมันบอกโครงสร้างของข้อความ
REPLACEMENTS = {
    "【": "[", "】": "]", "〔": "[", "〕": "]", "《": "[", "》": "]",
    "「": "[", "」": "]", "『": "[", "』": "]", "〖": "[", "〗": "]",
    "〈": "[", "〉": "]", "⁄": "/",   # ⁄ มาจาก NFKC ของ ½ -> "1⁄2" แปลงต่อเป็น "1/2"
    "“": '"', "”": '"', "„": '"', "‟": '"',
    "‘": "'", "’": "'", "‚": "'", "‛": "'",
    "–": "-", "—": "-", "―": "-", "‐": "-", "‑": "-", "─": "-",
    "…": "...", "•": "-", "·": "-", "∙": "-",
    " ": " ", " ": " ", " ": " ", "　": " ",  # ช่องว่างแบบต่าง ๆ
    "、": ",", "。": ".",
}

# --- ช่วงรหัสของไอคอน/อีโมจิที่จะลบทิ้ง ---------------------------------------
# เลือกเฉพาะช่วงที่เป็น "ภาพประกอบ" ล้วน ๆ ไม่ใช่ตัวอักษรหรือสัญลักษณ์ที่สื่อความหมาย
ICON_RANGES = [
    (0x2190, 0x21FF),    # ลูกศร → ← (ใช้ตกแต่งหัวข้อ ไม่ได้สื่อความหมายในบริบทนี้)
    (0x231A, 0x23FF),    # นาฬิกา/ปุ่มควบคุม ⌚ ⏰ ⏩ — เริ่มที่ 0x231A เพื่อเก็บ ⌀ (สัญลักษณ์เส้นผ่าศูนย์กลาง) ไว้
    (0x20D0, 0x20FF),    # เครื่องหมายผสมสำหรับสัญลักษณ์ — เศษที่ค้างจาก 1️⃣ 2️⃣
    (0x2500, 0x259F),    # เส้นกรอบและบล็อกทึบ ─ █ ▓
    (0x25A0, 0x25FF),    # รูปทรงเรขาคณิต ■ ● ▶ ◆
    (0x2600, 0x26FF),    # สัญลักษณ์เบ็ดเตล็ด ☀ ★ ⚡ ☑ ♥ ♫
    (0x2700, 0x27BF),    # เครื่องหมายตกแต่ง ✔ ✨ ❤ ➤ ✿
    (0x2B00, 0x2BFF),    # ลูกศร/ดาวเพิ่มเติม ⭐ ⬆
    (0xFE00, 0xFE0F),    # ตัวเลือกรูปแบบ (ตัวปรับอีโมจิที่มองไม่เห็น)
    (0x1F000, 0x1FAFF),  # อีโมจิทั้งหมด 💛 🎁 👍 🔥 💎
    (0xE000, 0xF8FF),    # พื้นที่ใช้ส่วนตัว (ฟอนต์เฉพาะ แสดงผลไม่ได้จริง)
]
_ICON_PATTERN = re.compile(
    "[" + "".join(f"\\U{lo:08X}-\\U{hi:08X}" for lo, hi in ICON_RANGES) + "]"
)

# อักขระควบคุมที่หลงมาในข้อความ (ยกเว้น tab/ขึ้นบรรทัดใหม่)
# รวม U+FFFD (�) ซึ่งเป็นสัญลักษณ์ที่โผล่เมื่อข้อความต้นฉบับเสียหายตอนแปลงรหัส — ไม่ใช่ข้อมูล
_CONTROL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f�]")

# ตัวอักษรต่างภาษาที่ผู้ขายหยิบมาใช้เป็นลวดลาย ไม่ได้ใช้เขียนภาษานั้นจริง
# ღ (จอร์เจีย) พบ 295 ครั้งในรูปแบบ "ღ ‿ ღ[หัวข้อ]" · ‿ ◟ ◝ ใช้ทำหน้ายิ้ม
_DECORATIVE_LETTERS = re.compile(r"[ღ‿⁀◖◗]")

_MULTISPACE = re.compile(r"[ \t]{2,}")

# ต้นฉบับเขียน 【หัวข้อ】รายละเอียด ติดกันโดยไม่เว้นวรรค (สไตล์การเขียนภาษาจีน)
# พอแปลงเป็น [หัวข้อ]รายละเอียด แล้วยังติดกันอยู่ อ่านยากและตอนแปลงเป็นเวกเตอร์จะแยกคำผิด
_AFTER_BRACKET = re.compile(r"([\]\)])(?=[A-Za-z0-9])")
# เว้นวรรคหลัง , : ; เมื่อตามด้วย "ตัวอักษร" เท่านั้น
# ไม่แตะเมื่อตามด้วยตัวเลข เพื่อไม่ให้ 1,000 กลายเป็น 1, 000 และ 10:30 เป็น 10: 30
_AFTER_PUNCT = re.compile(r"([,:;])(?=[A-Za-z])")
# เครื่องหมายวรรคตอนที่เหลือค้างหลังลบไอคอน เช่น "✅ - ข้อความ" -> "- ข้อความ"
_LEADING_JUNK = re.compile(r"^[\s\-–—:;,.|/\\]+")
_TRAILING_JUNK = re.compile(r"[\s\-–—:;,|/\\]+$")


def clean_text(text) -> str:
    """ทำความสะอาดข้อความหนึ่งก้อน

    ลำดับสำคัญ: normalize ก่อน แล้วค่อยแทนที่ แล้วค่อยลบไอคอน
    เพราะ NFKC จะแปลง `𝐄𝐚𝐬𝐲` -> `Easy`, `①` -> `1`, `℃` -> `°C`, `，` -> `,`
    ให้เองอยู่แล้ว ถ้าลบก่อนจะเสียตัวอักษรจริงไปด้วย
    """
    if not isinstance(text, str) or not text.strip():
        return ""

    # NFKC = แปลงตัวอักษรที่เขียนด้วยรหัสแปลกกลับเป็นตัวปกติ
    #   𝐄𝐚𝐬𝐲 𝐭𝐨 𝐔𝐬𝐞 -> Easy to Use  |  ①②③ -> 123  |  ℃ -> °C  |  ，： -> ,:
    out = unicodedata.normalize("NFKC", text)

    for source, target in REPLACEMENTS.items():
        out = out.replace(source, target)

    out = _ICON_PATTERN.sub(" ", out)
    out = _DECORATIVE_LETTERS.sub(" ", out)
    out = _CONTROL.sub("", out)
    out = _AFTER_BRACKET.sub(r"\1 ", out)
    out = _AFTER_PUNCT.sub(r"\1 ", out)
    out = _MULTISPACE.sub(" ", out)
    out = _LEADING_JUNK.sub("", out)
    out = _TRAILING_JUNK.sub("", out)
    return out.strip()


def clean_text_list(items) -> list[str]:
    """ทำความสะอาดลิสต์ข้อความ แล้วตัดข้อที่เหลือว่างหรือสั้นเกินกว่าจะมีความหมายทิ้ง"""
    if items is None:
        return []
    cleaned = []
    for item in items:
        text = clean_text(item)
        if len(text) >= 3:      # เหลือ 1-2 ตัวอักษรมักเป็นเศษที่ค้างจากไอคอน
            cleaned.append(text)
    return cleaned
